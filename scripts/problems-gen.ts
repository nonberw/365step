import fs from "node:fs";
import { SOURCES } from "./problems-src";

// Runs each reference solution on its tests and writes shared/problemsMore.ts: statements and tests with
// expected answers, without the solutions. Run: npx tsx scripts/problems-gen.ts

const snake = (s: string) => s.replace(/[A-Z]/g, (c) => `_${c.toLowerCase()}`);
const show = (v: unknown) => {
  const s = JSON.stringify(v);
  return s.length > 90 ? `${s.slice(0, 87)}…` : s;
};

const out = SOURCES.map((p) => {
  const tests = p.tests.map((args) => {
    const t0 = performance.now();
    const expected = (p.solve as (...a: unknown[]) => unknown)(...structuredClone(args));
    const ms = performance.now() - t0;
    if (ms > 500) console.warn(`${p.id}: reference solution took ${ms.toFixed(0)} ms`);
    return { args, expected };
  });
  const visible = p.visible ?? 2;
  return {
    id: p.id,
    title: p.title,
    difficulty: p.difficulty,
    pattern: p.pattern,
    tags: p.tags,
    name: p.name,
    pyName: snake(p.name),
    params: p.params,
    statement: p.statement,
    examples: tests.slice(0, visible).map((t) => ({ input: p.params.map((n, i) => `${n} = ${show(t.args[i])}`).join(", "), output: show(t.expected) })),
    constraints: p.constraints,
    tests,
    visible,
    hints: p.hints,
    ...(p.unordered ? { unordered: true } : {}),
  };
});

const ids = new Set<string>();
for (const p of out) {
  if (ids.has(p.id)) throw new Error(`duplicate id ${p.id}`);
  ids.add(p.id);
}
fs.writeFileSync(
  "shared/problemsMore.ts",
  `// Generated by scripts/problems-gen.ts from scripts/problems-src.ts — do not edit by hand.\n// Expected answers come from reference solutions that stay out of the app bundle.\n\nexport const MORE = ${JSON.stringify(out)} as const;\n`,
);
console.log(`${out.length} problems, ${out.reduce((s, p) => s + p.tests.length, 0)} tests → shared/problemsMore.ts (${(fs.statSync("shared/problemsMore.ts").size / 1024).toFixed(0)} KB)`);
